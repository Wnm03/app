#!/usr/bin/env node
'use strict';
const fs=require('node:fs');const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const read=r=>fs.readFileSync(path.join(ROOT,r),'utf8');
let bad=0; const fail=m=>{console.error('FAIL '+m);bad++;};
const build=read('scripts/build.js');
const idxA=build.indexOf("'modules/vehicle/car-notes-performance.js'");
const idxCore=build.indexOf("'modules/vehicle/vehicle-core.js'");
const idxSp=build.indexOf("'modules/vehicle/sparepart-servis.js'");
const idxUi=build.indexOf("'modules/vehicle/sparepart-servis-ui.js'");
const idxB=build.indexOf("'modules/vehicle/sparepart-servis-b.js'");
if(idxA<0||idxA>idxCore)fail('CarNotesPerformance is not registered before vehicle-core');
if(idxSp<0||idxUi<0||idxB<0||!(idxSp<idxUi&&idxUi<idxB))fail('Sparepart UI build order is invalid');
const core=read('modules/vehicle/vehicle-core.js');
if(!/const CNI_SUBTAB_ORDER=\['ringkasan','rekomendasi'\]/.test(core))fail('CNI_SUBTAB_ORDER missing');
if(!/const CNI_SUBTAB_LABEL=\{ringkasan:'Ringkasan',rekomendasi:'Rekomendasi & Tren'\}/.test(core))fail('CNI_SUBTAB_LABEL missing');
const perf=read('modules/vehicle/car-notes-performance.js');
for(const x of ['inventory','memo','auditCurrent','snapshot'])if(!new RegExp('\\b'+x+'\\b').test(perf))fail('CarNotesPerformance API missing: '+x);
const css=read('styles.css');
if(!css.includes('#servisReminderCard-cbody .servis-reminder-list') || !/servisReminderCard-cbody \.servis-reminder-list[^}]*overflow-y\s*:\s*auto/.test(css))fail('servis reminder internal scroll missing');
if(fs.existsSync(path.join(ROOT,'modules/vehicle/'+['pro','mockup','presenter'].join('-')+'.js')))fail('retired Theme Pro presenter still exists');
const index=read('index.html');
const retiredTokens=['pro'+'Mockup','pro'+'CnBottomNav','pro'+'-ui-layer'];
if(/data-theme=["']pro["']/.test(index) || retiredTokens.some(t=>index.includes(t)))fail('Theme Pro residue in index.html');
const source=read('modules/vehicle/sparepart-servis-ui.js');
if(!/renderStockList\(\)/.test(source))fail('Sparepart.renderStockList implementation missing');
console.log(`Car Notes runtime contracts: ${bad?'FAIL':'PASS'}`);
process.exit(bad?1:0);
