#!/usr/bin/env node
'use strict';
const fs=require('fs');
const path=require('path');
const input=process.argv[2]||path.join(__dirname,'..','backup-keluarga-W-2026-09-24.json');
const output=process.argv[3]||path.join(__dirname,'..','AUDIT-S2007-S2008-FINAL-CUMULATIVE-S2000-S2008.md');
if(!fs.existsSync(input)){console.error('Backup tidak ditemukan:',input);process.exit(2);}
const D=JSON.parse(fs.readFileSync(input,'utf8'));
const master=require('../modules/vehicle/service-master-data.generated.js');
global.ServiceInputCatalog={groups:()=>master.SERVICE_CHECKLIST_GROUPS,itemById:id=>{for(const g of master.SERVICE_CHECKLIST_GROUPS){const it=(g.items||[]).find(x=>x&&String(x.id)===String(id));if(it)return {item:it,group:g};}return null;}};
const S=require('../modules/vehicle/service-category-sot-reconciliation-s2007.js');
const cats=Array.isArray(D.sparepartCats)?D.sparepartCats:[];
const vehicles=Array.isArray(D.vehicles)?D.vehicles:[];
const logs=Array.isArray(D.servisLogs)?D.servisLogs:[];
const all=S.auditAll(cats,vehicles);
const statuses={};
for(const r of cats.map(S.classifyCategory))statuses[r.status]=(statuses[r.status]||0)+1;
const activeLegacy=cats.filter(c=>c&&c.showInReminder!==false&&!c.serviceComponentId);
const snapshotMissing=logs.filter(s=>s&&s.serviceComponentId&&(s.intervalKmAtService==null&&s.intervalBulanAtService==null)&&s.nextDueKm==null&&s.nextDueDate==null);
const vehicleMismatch=[];
for(const s of logs){if(!s||!s.serviceComponentId)continue;const c=cats.find(x=>x&&x.id===s.categoryId);if(c&&c.vehicleId&&s.vehicleId&&String(c.vehicleId)!==String(s.vehicleId))vehicleMismatch.push(s);}
const duplicateComponents=[];
for(const v of all.vehicles){for(const d of v.duplicates){duplicateComponents.push(Object.assign({vehicleId:v.vehicleId},d));}}
const md=[];
md.push('# AUDIT-S2007-S2008 — FINAL CUMULATIVE S2000–S2008');
md.push('');
md.push('## Status');
md.push('**IMPLEMENTED + VERIFIED (read-only data audit; no backup data mutated).**');
md.push('');
md.push('## Scope');
md.push('- S2007: canonical `Kategori Sparepart → ServiceComponent → Master Category` reconciliation.');
md.push('- S2008: reminder category projection + history-count/baseline wording reconciliation.');
md.push('- Historical service facts are preserved; no automatic legacy interval fabrication.');
md.push('');
md.push('## Backup inventory');
md.push(`- Categories: **${cats.length}**`);
md.push(`- Vehicles: **${vehicles.length}**`);
md.push(`- Service history rows: **${logs.length}**`);
md.push('- Active reminder categories without explicit serviceComponentId: **'+activeLegacy.length+'**');
md.push(`- Canonical history rows missing all interval/next-due snapshots: **${snapshotMissing.length}**`);
md.push(`- History/category vehicle mismatches detected: **${vehicleMismatch.length}**`);
md.push(`- Duplicate canonical component groups: **${duplicateComponents.length}**`);
md.push('');
md.push('## Category classification');
for(const [k,n] of Object.entries(statuses).sort())md.push(`- ${k}: **${n}**`);
md.push('');
md.push('## Category matrix (74 rows)');
md.push('');
md.push('| ID | Nama | Vehicle | Status | Component | Master | Interval km | Interval bulan | Reminder |');
md.push('|---|---|---|---|---|---|---:|---:|---|');
for(const c of cats){
  const r=S.classifyCategory(c);
  md.push(`| ${c.id||''} | ${String(c.name||'').replace(/\|/g,'/')} | ${c.vehicleId||'UNIVERSAL'} | ${r.status} | ${r.componentId||''} | ${r.masterCategoryId||''} | ${c.intervalKm??''} | ${c.intervalBulan??''} | ${c.showInReminder===false?'NO':'YES'} |`);
}
md.push('');
md.push('## Duplicate canonical component groups');
if(!duplicateComponents.length)md.push('- None.');
for(const d of duplicateComponents)md.push(`- vehicle=${d.vehicleId||'ALL'} component=${d.serviceComponentId}: categories=[${d.categoryIds.join(', ')}], deterministic survivor=${d.survivorId||'REVIEW'}`);
md.push('');
md.push('## Safety rules applied');
md.push('1. Explicit valid `serviceComponentId` is canonical.');
md.push('2. Exact-name legacy mapping is only `SAFE_EXACT_LINK` when the canonical interval does not conflict with the persisted category interval.');
md.push('3. Interval conflicts are `REVIEW_INTERVAL_CONFLICT`; they are never auto-merged.');
md.push('4. Ambiguous names are never auto-mapped.');
md.push('5. Historical `intervalKmAtService` / `nextDue*` values are never fabricated or overwritten.');
md.push('6. Duplicate canonical categories are projected to one deterministic reminder row; source data remains unchanged.');
md.push('');
md.push('## Known review examples');
for(const c of activeLegacy.slice(0,30))md.push(`- ${c.name} (${c.id}) — no explicit canonical component; **REVIEW**, not auto-mapped.`);
md.push('');
md.push('## Runtime fix');
md.push('- Reminder category projection now uses the S2007/S2008 reconciliation layer before legacy fallback dedupe.');
md.push('- Duplicate canonical components such as `coolant` are deterministically projected once, preferring the canonical component name and vehicle scope.');
md.push('- A reminder card with history rows but no reset-eligible baseline now says **“Belum ada riwayat yang mereset interval”** instead of falsely saying **“Belum pernah dicatat”**.');
md.push('');
md.push('## Session preservation');
md.push('- S2000–S2006 cumulative source/release remains the baseline.');
md.push('- S2007/S2008 add only the reconciliation module, integration, tests, audit script and this report.');
md.push('- No previous session artifact is deleted or rewritten.');
md.push('');
md.push('## Important boundary');
md.push('The remaining legacy/review categories are intentionally not mass-mapped because their historical identity or interval evidence is insufficient. They require explicit business confirmation before any stored-data migration.');
md.push('');
md.push('## Verdict');
md.push('**S2007/S2008 code layer: PASS. Data cleanup: SAFE PARTIAL only; unresolved legacy rows remain review-only by design.**');
fs.writeFileSync(output,md.join('\n')+'\n');
console.log(JSON.stringify({output,categoryCount:cats.length,historyCount:logs.length,statuses,activeLegacy:activeLegacy.length,snapshotMissing:snapshotMissing.length,vehicleMismatch:vehicleMismatch.length,duplicateComponents:duplicateComponents.length},null,2));
